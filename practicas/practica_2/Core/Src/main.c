		if (delayRead(&led_delay)) {
			HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);
			led_sequence.toggle_count++;

			// 2 toggles = 1 blink completo (ON+OFF)
			if (led_sequence.toggle_count >= (blink_steps[led_sequence.step_index].toggles * 2)) {
				led_sequence.toggle_count = 0;
				led_sequence.step_index = (led_sequence.step_index + 1) % led_sequence.total_steps;
				delayWrite(&led_delay, blink_steps[led_sequence.step_index].duration);
			}
		}
#else

		// Punto 2: parpadeo no bloqueante //
		if (delayRead(&led_delay)) {
			HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);
		}
